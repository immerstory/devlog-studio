import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import type { Format, Material, Post, Segment } from "../shared/types.js";
import { spawnCollect } from "./agent.js";
import { config } from "./config.js";
import { projectId } from "./context.js";
import { throwIfCancelled } from "./jobs.js";
import { ingestFile } from "./materials.js";
import { loadPost, updatePost } from "./store.js";

type Log = (line: string) => void;

/** Creates one image from a prompt and returns the path of the file. */
export interface ImageGenerator {
  id: "codex";
  label: string;
  generate(prompt: string, format: Format, log: Log): Promise<string>;
}

/** What every generated image keeps to: an illustration of the idea, never a document of something real. */
export const IMAGE_RULES = "An illustrative scene for a short video, not a document of a real event. No logos, brand names, trademarks or readable text. No real or identifiable people; people, if any, are generic and seen from behind or at a distance. Devices look generic, not like a specific product.";

/** The prompt for a segment: the description of the footage it asks for, without the instruction to record it. */
export function imagePrompt(description: string, format: Format): string {
  const subject = description.replace(/^\s*(to record|record|footage to record)\b[^:]*:\s*/i, "").trim();
  return `${subject}\n\nFormat: ${format === "portrait" ? "vertical 9:16" : "horizontal 16:9"}, photographic, natural light.\n${IMAGE_RULES}`;
}

const codexHome = () => process.env.CODEX_HOME || path.join(os.homedir(), ".codex");

/**
 * Codex's built-in image_gen tool, in a read-only session. Codex keeps the image under its home folder, in a folder
 * named after the session, so nothing in the project is written.
 */
export const codexImages: ImageGenerator = {
  id: "codex",
  label: "Codex",
  async generate(prompt, format, log) {
    const c = config().agent.codex;
    const args = [...c.args, "exec", "--sandbox", "read-only", "--skip-git-repo-check", "--ephemeral", "--json"];
    if (c.model) args.push("-m", c.model);
    args.push("-");
    const instruction = `Use your built-in image_gen tool to generate exactly one image. Do not write or change any files. When the image exists, reply with only the word done.\n\nImage:\n${prompt}`;
    log(`codex: generating an image (${format})…`);
    const { stdout, stderr, code } = await spawnCollect(c.executable, args, instruction, log);
    const thread = /"thread_id":"([^"]+)"/.exec(stdout)?.[1];
    const dir = thread ? path.join(codexHome(), "generated_images", thread) : "";
    const files = dir && fs.existsSync(dir) ? fs.readdirSync(dir).filter((f) => /\.(png|jpe?g|webp)$/i.test(f)).map((f) => path.join(dir, f)) : [];
    if (!files.length) throw new Error(`Codex generated no image (exit ${code}). Check that Codex is signed in and offers its image_gen tool. ${stderr.slice(-400)}`.trim());
    return files.sort((a, b) => fs.statSync(b).mtimeMs - fs.statSync(a).mtimeMs)[0];
  },
};

export const imageGenerators = { codex: codexImages } as const;

/** Material segments of a script that ask for footage and have none yet. */
export const missingImages = (post: Post, format: Format) =>
  (post.scripts[format]?.segments ?? []).filter((s): s is Segment & { visual: { type: "material" } } => s.visual.type === "material" && !s.visual.materialId && !!s.visual.description.trim());

/**
 * Generates an image for each material segment that has none, or for one segment, stores it as a material marked
 * as generated, and attaches it. A failed image leaves its segment as it was and the next one still runs.
 */
export async function generateSegmentImages(postId: string, format: Format, log: Log, segmentId?: string, generator: ImageGenerator = codexImages) {
  const pid = projectId();
  const post = await loadPost(pid, postId);
  const segments = segmentId
    ? (post.scripts[format]?.segments ?? []).filter((s) => s.id === segmentId && s.visual.type === "material")
    : missingImages(post, format);
  if (!segments.length) { log("No material segment needs an image."); return { generated: 0, failed: 0 }; }
  let generated = 0, failed = 0;
  for (const seg of segments) {
    throwIfCancelled();
    const description = seg.visual.type === "material" ? seg.visual.description : "";
    const prompt = imagePrompt(description, format);
    try {
      const file = await generator.generate(prompt, format, log);
      const material: Material = await ingestFile(file, `generated-${seg.id}${path.extname(file)}`, {
        date: post.publishDate,
        title: description.replace(/^\s*(to record|record)\b[^:]*:\s*/i, "").slice(0, 80),
        annotation: `Generated by ${generator.label}. Prompt: ${prompt}`,
        tags: ["ai-generated"],
        generated: { tool: generator.id, prompt },
      });
      await updatePost(pid, postId, (p) => {
        const target = p.scripts[format]?.segments.find((s) => s.id === seg.id);
        if (target?.visual.type === "material") {
          target.visual = { ...target.visual, materialId: material.id, framing: undefined };
          // The segment now has its footage, so the capture's note to record it no longer applies.
          delete target.captureError;
        }
        if (!p.materialIds.includes(material.id)) p.materialIds.push(material.id);
      });
      log(`Segment ${(post.scripts[format]?.segments.indexOf(seg) ?? 0) + 1}: image added as a material.`);
      generated++;
    } catch (err) {
      if ((err as Error).name === "CancelledError") throw err;
      failed++;
      log(`Segment ${(post.scripts[format]?.segments.indexOf(seg) ?? 0) + 1}: ${(err as Error).message}`);
    }
  }
  log(`${generated} image(s) generated${failed ? `, ${failed} failed` : ""}.`);
  if (generated === 0 && failed) throw new Error("No image could be generated.");
  return { generated, failed };
}
